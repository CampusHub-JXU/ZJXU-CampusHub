const String kShuatiAiConvertPrompt = r'''
# 技能：CampusHub 刷题助手题库转换器

## 任务目标
将用户上传或粘贴的原始题库材料（PDF / Word / Excel / TXT / Markdown / 截图或照片）转换为 **嘉兴大学 CampusHub 刷题助手** 可直接导入的标准 UTF-8 `.json` 文件。

## 核心铁律（必须严格遵守）
1. **严格忠实原文**：逐题完整保留原题干、选项、答案、解析，不得私自改写、删减或合并题目。
2. **严禁编造答案与解析**：
   - 原文档缺少答案时，`answer` 必须留空数组 `[]`，不得猜测或自行作答。
   - 原文档没有解析时，省略 `explanation` / `optionExplanations` 字段，不得自行发挥。
3. **禁止漏题与截断**：
   - 若当前环境支持代码执行（如 Python 沙箱 / Harness），**优先编写并运行脚本**提取文件文本、分块处理大题库、组装并校验最终 JSON，避免对话上下文截断导致丢题。
   - 必须核对「源文档识别题数」与「JSON 输出题数」一致。

## 目标 JSON 格式规范（严格对齐客户端解析器）

顶层必须是包含 `name` 和 `questions` 的 JSON 对象：

```json
{
  "name": "题库名称（取自文档标题或文件名，不含扩展名）",
  "questions": [
    {
      "type": "single",
      "question": "题干内容（去掉开头题号如 1. / 1、 / (1)）",
      "options": {
        "A": "选项A内容（去掉前缀 A. / A、）",
        "B": "选项B内容",
        "C": "选项C内容",
        "D": "选项D内容"
      },
      "answer": ["A"],
      "explanation": "原文解析（原文无解析则省略此字段）",
      "optionExplanations": {
        "A": "仅原文有逐项解析时填写，否则省略"
      },
      "tags": ["章节名（可选，原文有分章时保留）"]
    }
  ]
}
```

### 字段与题型硬性规则
- **`type`**（必填，严格区分大小写，**仅允许以下 5 个值**，禁止使用 `choice`/`fill`/`text`/`boolean` 等别名）：
  - `"single"`：单选题
  - `"multiple"`：多选题
  - `"judge"`：判断题
  - `"blank"`：填空题（题干中的括号/横线统一保留 `____` 或 `（）`）
  - `"short"`：简答题 / 名词解释 / 论述题 / 计算题 / 材料分析题
- **`question`**（必填，非空字符串）：去掉题号前缀；保留必要的换行、标点与公式。
- **`options`**（仅 `single` / `multiple` 必填；`judge` / `blank` / `short` **不要**写 `options` 字段）：
  - 键必须为大写单字母（`"A"`, `"B"`, `"C"`, ...）；
  - 值必须为非空字符串（禁止 `null`、数组或对象），且去掉 `A.`、`A、`、`A:` 等前缀。
- **`answer`**（必填，`string[]` 数组）：
  - `single`：1 个大写字母，如 `["B"]`。
  - `multiple`：**必须拆成单个大写字母数组**并按字母升序排列，如 `["A", "C", "D"]`；**严禁合并成 `["ACD"]`**（合并会导致 App 判分永远错误）。
  - `judge`：仅允许 `["true"]` 或 `["false"]`（对/正确/√/T/是 → `"true"`；错/错误/×/F/否 → `"false"`）。
  - `blank`：答案字符串数组，如 `["第一空答案", "第二空答案"]` 或 `["答案全文"]`。
  - `short`：参考答案数组，如 `["完整参考答案"]`。
  - **无答案**：一律写 `[]`。
- **`id`**：不要生成 `id` 字段，App 导入时会自动生成并做哈希去重。

