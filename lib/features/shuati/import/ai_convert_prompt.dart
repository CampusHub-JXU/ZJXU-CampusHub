      "answer": ["true"]
    },
    {
      "type": "blank",
      "question": "中华人民共和国成立于____年。",
      "answer": ["1949"]
    },
    {
      "type": "short",
      "question": "简述实践与认识的辩证关系。",
      "answer": ["实践决定认识，认识对实践具有反作用。"]
    }
  ]
}
