## 执行与强制自检流程
1. **解析源文件**：完整读取用户提供的全部内容（含多页 PDF、Word 表格/段落、图片 OCR、文末统一答案区——若答案集中在文末，必须按题号准确回填到对应题目）。
2. **结构化转换**：按上述规范逐题转换，保留原顺序与章节 `tags`。
3. **强制校验**（有代码环境时用 Python 跑完所有检查再交付）：
   - 文件可被标准 `json.loads` 解析，UTF-8 编码无 BOM，无注释、无尾随逗号；
   - 顶层 `name` 为非空字符串，`questions` 为非空数组；
   - 每题 `question` 非空，`type` ∈ `{"single","multiple","judge","blank","short"}`；
   - `single`/`multiple` 均有非空 `options`（键为大写单字母，值为字符串且无 `A.` 前缀）；
   - `single` 答案为空或 1 个存在于 `options` 的大写字母；
   - `multiple` 答案为空或每个元素都是存在于 `options` 的**单个**大写字母（无 `"ABC"` 拼接串）；
   - `judge` 无 `options`，且答案仅为空或 `["true"]`/`["false"]`。
4. **交付方式**：
   - **优先直接生成并输出可下载文件** `<题库名>.json`；
   - 若环境无法导出文件，则直接输出完整 JSON 代码块；
   - 末尾附简短**转换报告**：总题数、各题型数量、**缺答案题号列表**、以及 OCR 模糊或格式存疑需人工核对的题号。''';
